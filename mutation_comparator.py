def generate_csv_report(results: list, unpaired: list, output_path: Path):
    """Generate summary CSV report (openable in Excel)."""
    with open(output_path, 'w', newline='', encoding='utf-8-sig') as f:
        writer = csv.writer(f)
        writer.writerow([
            'STT', 'Mẫu (Sample)', 'File Người 1', 'File Người 2',
            'Mutations F1', 'Mutations F2', 'Trùng khớp',
            'Chỉ F1', 'Chỉ F2', 'Tỷ lệ giống (%)', 'Kết quả'
        ])

        for i, r in enumerate(results, 1):
            comp = r['comparison']
            status = 'TRÙNG KHỚP' if comp['is_match'] else 'KHÁC BIỆT'

            writer.writerow([
                i,
                r['base_name'],
                r['file_1'].name,
                r['file_2'].name,
                comp['total_1'],
                comp['total_2'],
                comp['matched_count'],
                len(comp['only_in_1']),
                len(comp['only_in_2']),
                f"{comp['similarity']}%",
                status,
            ])

        # Append unpaired files at the bottom
        for uf in unpaired:
            writer.writerow([
                '', '', uf.name, '—',
                '', '', '', '', '', '', 'KHÔNG CÓ CẶP',
            ])


def generate_diff_detail(result: dict, output_path: Path):
    """Generate detailed diff report for a single pair."""
    comp = result['comparison']

    with open(output_path, 'w', encoding='utf-8') as f:
        f.write(f"{'=' * 70}\n")
        f.write(f"  MẪU: {result['base_name']}\n")
        f.write(f"{'=' * 70}\n")
        f.write(f"  File 1 (Người 1): {result['file_1'].name}\n")
        f.write(f"  File 2 (Người 2): {result['file_2'].name}\n")
        f.write(f"  Mutations: F1={comp['total_1']}, F2={comp['total_2']}\n")
        f.write(f"  Tỷ lệ giống: {comp['similarity']}%\n")
        f.write(f"{'=' * 70}\n\n")

        # Matched mutations
        f.write(f"--- TRÙNG KHỚP ({comp['matched_count']} mutations) ---\n")
        if comp['matched']:
            f.write(f"  {'Pos':<12} {'Seq':<8} {'Con':<8} {'Required Edit'}\n")
            f.write(f"  {'-'*12} {'-'*8} {'-'*8} {'-'*15}\n")
            for m in comp['matched']:
                f.write(f"  {m[0]:<12} {m[1]:<8} {m[2]:<8} {m[3]}\n")
        else:
            f.write("  (không có)\n")
        f.write("\n")

        # Only in File 1
        f.write(f"--- CHỈ CÓ Ở FILE 1 - Người 1 ({len(comp['only_in_1'])} mutations) ---\n")
        if comp['only_in_1']:
            f.write(f"  {'Pos':<12} {'Seq':<8} {'Con':<8} {'Required Edit'}\n")
            f.write(f"  {'-'*12} {'-'*8} {'-'*8} {'-'*15}\n")
            for m in comp['only_in_1']:
                f.write(f"  {m[0]:<12} {m[1]:<8} {m[2]:<8} {m[3]}\n")
        else:
            f.write("  (không có)\n")
        f.write("\n")

        # Only in File 2
        f.write(f"--- CHỈ CÓ Ở FILE 2 - Người 2 ({len(comp['only_in_2'])} mutations) ---\n")
        if comp['only_in_2']:
            f.write(f"  {'Pos':<12} {'Seq':<8} {'Con':<8} {'Required Edit'}\n")
            f.write(f"  {'-'*12} {'-'*8} {'-'*8} {'-'*15}\n")
            for m in comp['only_in_2']:
                f.write(f"  {m[0]:<12} {m[1]:<8} {m[2]:<8} {m[3]}\n")
        else:
            f.write("  (không có)\n")


def classify_files(results: list, unpaired: list, output_dir: Path, logger):
    """Copy files into matched/mismatched/unpaired subdirectories."""
    matched_dir = output_dir / 'matched'
    mismatched_dir = output_dir / 'mismatched'
    unpaired_dir = output_dir / 'unpaired'

    for d in [matched_dir, mismatched_dir, unpaired_dir]:
        d.mkdir(parents=True, exist_ok=True)

    matched_count = 0
    mismatched_count = 0

    for r in results:
        target_dir = matched_dir if r['comparison']['is_match'] else mismatched_dir
        shutil.copy2(r['file_1'], target_dir / r['file_1'].name)
        shutil.copy2(r['file_2'], target_dir / r['file_2'].name)
        if r['comparison']['is_match']:
            matched_count += 2
        else:
            mismatched_count += 2

    for uf in unpaired:
        shutil.copy2(uf, unpaired_dir / uf.name)

    logger.info(f"  Copied {matched_count} files → matched/")
    logger.info(f"  Copied {mismatched_count} files → mismatched/")
    if unpaired:
        logger.info(f"  Copied {len(unpaired)} files → unpaired/")


