def auto_pair_files(directory: Path) -> tuple:
    """
    Scan directory and pair files that differ only by _1/_2 suffix.
    
    Example:
        NC_012920.1 vs D05_L1-R639_20260718_113222_1.txt  ─┐
        NC_012920.1 vs D05_L1-R639_20260718_113222_2.txt  ─┘ pair
        
    Returns:
        (pairs, unpaired) where:
            pairs    = [(file1_path, file2_path), ...]
            unpaired = [filepath, ...]
    """
    groups = defaultdict(dict)

    for f in sorted(directory.glob('*.txt')):
        match = SUFFIX_PATTERN.match(f.name)
        if match:
            base_name = match.group(1)   # everything before _1 or _2
            suffix_num = match.group(2)  # "1" or "2"
            groups[base_name][suffix_num] = f

    pairs = []
    unpaired = []

    for base_name, files in sorted(groups.items()):
        if '1' in files and '2' in files:
            pairs.append((files['1'], files['2']))
        else:
            for f in files.values():
                unpaired.append(f)

    return pairs, unpaired


