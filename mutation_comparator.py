# Regex to match file naming: ...._1.txt and ...._2.txt
SUFFIX_PATTERN = re.compile(r'^(.+)_([12])\.txt$', re.IGNORECASE)

# Regex to find the header row in the mutation table
HEADER_PATTERN = re.compile(r'^\s*Pos\s+Seq\s+Con\s+Required\s+Edit\s*$', re.IGNORECASE)

# Regex to extract the difference count from the first line
DIFF_COUNT_PATTERN = re.compile(r'^(\d+)\s+differences?\s+between', re.IGNORECASE)

# Encodings to try (Sequencher 5.4.6 typically outputs Windows-1252)
ENCODINGS_TO_TRY = ['utf-8-sig', 'utf-8', 'cp1252', 'latin-1']

# Enable colored console output and UTF-8 on Windows
if sys.platform == 'win32':
    os.system('')  # Enable ANSI escape codes on Windows 10+
    # Force UTF-8 output to handle Vietnamese and box-drawing characters
    sys.stdout.reconfigure(encoding='utf-8', errors='replace')
    sys.stderr.reconfigure(encoding='utf-8', errors='replace')


