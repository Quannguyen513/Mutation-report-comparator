# MUTATION COMPARISON
# ============================================================

def _sort_key(pos_str: str) -> float:
    """Convert position string to sortable number. Handles '16,304' and '302.1'."""
    clean = pos_str.replace(',', '')
    try:
        return float(clean)
    except ValueError:
        return 0.0


def compare_mutations(mutations_1: list, mutations_2: list) -> dict:
    """
    Compare two sets of mutations using set-based comparison.
    
    This correctly handles cases where:
    - Files have different numbers of mutations
    - Mutations appear in different order
    - Same position but different Seq/Con/Edit values
    
    Returns:
        dict with keys:
            matched     - list of tuples present in both files
            only_in_1   - list of tuples only in file 1
            only_in_2   - list of tuples only in file 2
            total_1     - total mutations in file 1
            total_2     - total mutations in file 2
            matched_count - number of matched mutations
            similarity  - percentage similarity
            is_match    - True if 100% identical
    """
    set_1 = set(mutations_1)
    set_2 = set(mutations_2)

    matched = sorted(set_1 & set_2, key=lambda x: _sort_key(x[0]))
    only_in_1 = sorted(set_1 - set_2, key=lambda x: _sort_key(x[0]))
    only_in_2 = sorted(set_2 - set_1, key=lambda x: _sort_key(x[0]))

    total_unique = len(set_1 | set_2)
    similarity = (len(matched) / total_unique * 100) if total_unique > 0 else 100.0

    return {
        'matched': matched,
        'only_in_1': only_in_1,
        'only_in_2': only_in_2,
        'total_1': len(mutations_1),
        'total_2': len(mutations_2),
        'matched_count': len(matched),
        'similarity': round(similarity, 1),
        'is_match': len(only_in_1) == 0 and len(only_in_2) == 0,
    }


