# MUTATION FILE PARSER
# ============================================================

def parse_mutation_file(filepath: Path) -> dict:
    """
    Parse a Sequencher mutation report file.
    
    Expected format:
        9 differences between
        NC_012920.1 and the consensus.
        
        LEGEND:
        Pos - Offset in NC_012920.1.
        Seq - Base in NC_012920.1.
        ...
        
            Pos       Seq           Con         Required Edit
        
             73        A             G           Change base
            150        C             T           Change base

    Returns:
        dict with keys:
            - diff_count (int): number from header line
            - mutations (list): list of tuples (Pos, Seq, Con, RequiredEdit)
            - filepath (Path): source file path
    """
    content = read_file_with_encoding(filepath)
    lines = content.splitlines()

    result = {
        'diff_count': 0,
        'mutations': [],
        'filepath': filepath,
    }

    # Extract diff count from header
    for line in lines:
        match = DIFF_COUNT_PATTERN.match(line.strip())
        if match:
            result['diff_count'] = int(match.group(1))
            break

    # Find header row, then parse data rows after it
    header_found = False
    for line in lines:
        if header_found:
            stripped = line.strip()
            if not stripped:
                continue

            # Parse whitespace-delimited columns
            # Example: "302.1     :             C           Insert base"
            # Note: "Required Edit" value can be multi-word (e.g. "Change base")
            parts = stripped.split()
            if len(parts) >= 4:
                pos = parts[0]
                seq = parts[1]
                con = parts[2]
                required_edit = ' '.join(parts[3:])
                result['mutations'].append((pos, seq, con, required_edit))

        elif HEADER_PATTERN.match(line):
            header_found = True

    # Sanity check
    if result['diff_count'] != len(result['mutations']):
        logging.warning(
            f"  ⚠ {filepath.name}: Header says {result['diff_count']} differences "
            f"but parsed {len(result['mutations'])} data rows"
        )

    return result


