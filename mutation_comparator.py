# ============================================================
# FILE READING
# ============================================================

def read_file_with_encoding(filepath: Path) -> str:
    """
    Read a text file, trying multiple encodings.
    Sequencher may output in different encodings depending on system locale.
    """
    for enc in ENCODINGS_TO_TRY:
        try:
            return filepath.read_text(encoding=enc)
        except (UnicodeDecodeError, UnicodeError):
            continue
    raise UnicodeDecodeError(
        'multi', b'', 0, 1,
        f"Cannot decode {filepath.name} with any of: {ENCODINGS_TO_TRY}"
    )


